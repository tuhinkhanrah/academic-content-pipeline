"""Rebuild hierarchical Moodle imports from categorized question XML files."""

import hashlib
import json
import os
import re
import tempfile
from pathlib import Path
from xml.dom import Node, minidom
from xml.parsers.expat import ExpatError


LEGACY_COMBINED_NAME = "combined_moodle.xml"
COMBINED_SUFFIX = "_combined_moodle.xml"
OWNER = "Generated by academic-content-pipeline hierarchical Moodle combiner"
PREFIX = f'<?xml version="1.0" encoding="UTF-8"?>\n<quiz>\n<!-- {OWNER} -->\n'


def combined_name_for_directory(directory: Path) -> str:
    """Return a descriptive combined XML filename for its containing directory."""
    directory_name = re.sub(r"[^a-z0-9]+", "_", Path(directory).name.casefold()).strip("_")
    return f"{directory_name or 'root'}{COMBINED_SUFFIX}"


def _is_combined(path: Path) -> bool:
    name = path.name.casefold()
    return name == LEGACY_COMBINED_NAME or name.endswith(COMBINED_SUFFIX)


def _source_questions(path: Path, data: bytes) -> list[str] | None:
    try:
        document = minidom.parseString(data)
    except ExpatError as exc:
        raise ValueError(f"Cannot parse XML while combining: {path}: {exc}") from exc
    root = document.documentElement
    if root.tagName != "quiz":
        return None
    elements = [node for node in root.childNodes if node.nodeType == Node.ELEMENT_NODE]
    if any(node.tagName != "question" or not node.getAttribute("type") for node in elements):
        raise ValueError(f"Invalid Moodle question XML: {path}")
    categories = [node for node in elements if node.getAttribute("type") == "category"]
    if elements and len(categories) == len(elements):
        return None
    if len(categories) != 1 or not elements or elements[0] is not categories[0]:
        raise ValueError(
            f"Expected one leading category in Moodle XML: {path}. "
            "Add a category to this file before rebuilding combined XML."
        )
    texts = categories[0].getElementsByTagName("text")
    if not texts or not any(
        node.nodeType in (Node.TEXT_NODE, Node.CDATA_SECTION_NODE) and node.data.strip()
        for node in texts[0].childNodes
    ):
        raise ValueError(f"Empty Moodle category in XML: {path}")
    return [node.toxml() for node in elements]


def _owned_combined(path: Path) -> bool:
    prefix = PREFIX.encode("utf-8")
    with path.open("rb") as handle:
        header = handle.read(len(prefix) * 2)
    return header.replace(b"\r\n", b"\n").startswith(prefix)


def _atomic_write(path: Path, data: bytes) -> None:
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".moodle-combined-", delete=False) as handle:
            temporary = Path(handle.name)
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def _read_checkpoint(path: Path) -> dict:
    if path.is_symlink():
        raise ValueError(f"Checkpoint is a symlink: {path}")
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"Cannot read checkpoint {path}: {exc}") from exc
    if not isinstance(manifest, dict):
        raise ValueError(f"Invalid checkpoint: {path}")
    return manifest


def _checkpoint_output(directory: Path, name: object, checkpoint: Path) -> Path:
    if not isinstance(name, str) or not name or Path(name).name != name or "/" in name or "\\" in name:
        raise ValueError(f"Invalid checkpoint output filename: {checkpoint}")
    return directory / name


def _check_checkpoints(source_hashes: dict[Path, str]) -> None:
    for path, actual_hash in source_hashes.items():
        checkpoint = path.with_suffix(".extract.json")
        if checkpoint.exists():
            manifest = _read_checkpoint(checkpoint)
            if (
                manifest.get("schema_version") != 1
                or manifest.get("status") != "completed"
                or manifest.get("output_file") != path.name
                or manifest.get("final_sha256") != actual_hash
            ):
                raise ValueError(f"Extraction checkpoint is incomplete or does not match: {checkpoint}")

    for directory in {path.parent for path in source_hashes}:
        for checkpoint in sorted(directory.glob("*_batch_generation.json")):
            manifest = _read_checkpoint(checkpoint)
            items = manifest.get("items")
            if not isinstance(items, list) or not all(isinstance(item, dict) for item in items):
                raise ValueError(f"Invalid batch checkpoint: {checkpoint}")
            outputs = [_checkpoint_output(directory, item.get("output_file"), checkpoint) for item in items]
            if not source_hashes.keys() & set(outputs):
                continue
            if manifest.get("schema_version") != 2 or manifest.get("status") != "completed":
                raise ValueError(f"Batch checkpoint is incomplete or unsupported: {checkpoint}")
            if len(outputs) != len(set(outputs)):
                raise ValueError(f"Duplicate batch checkpoint output: {checkpoint}")
            for item, path in zip(items, outputs):
                if (
                    path not in source_hashes
                    or item.get("status") != "completed"
                    or source_hashes[path] != item.get("output_sha256")
                ):
                    raise ValueError(f"Batch checkpoint output is missing or changed: {path}")
        for checkpoint in sorted(directory.glob("*_question_types.json")):
            manifest = _read_checkpoint(checkpoint)
            names = manifest.get("files")
            if not isinstance(names, list):
                raise ValueError(f"Invalid question-generation checkpoint: {checkpoint}")
            outputs = [_checkpoint_output(directory, name, checkpoint) for name in names]
            if not source_hashes.keys() & set(outputs):
                continue
            if (
                manifest.get("status") != "completed"
                or manifest.get("completed_files") != names
                or len(outputs) != len(set(outputs))
                or any(path not in source_hashes for path in outputs)
            ):
                raise ValueError(f"Question-generation checkpoint is incomplete or missing outputs: {checkpoint}")


def _rebuild_combined_xml(root: Path) -> list[Path]:
    sections: dict[Path, list[str]] = {}
    source_hashes: dict[Path, str] = {}
    existing_combined: list[Path] = []
    for folder, directories, filenames in os.walk(root, followlinks=False):
        directories[:] = sorted(
            name for name in directories
            if not name.startswith(".") and not (Path(folder) / name).is_symlink()
        )
        for filename in sorted(filenames):
            path = Path(folder) / filename
            if _is_combined(path):
                if path.is_symlink():
                    raise ValueError(f"Combined XML is a symlink: {path}")
                existing_combined.append(path)
                continue
            if path.suffix.casefold() != ".xml":
                continue
            if path.is_symlink() or not path.resolve().is_relative_to(root):
                raise ValueError(f"XML is a symlink or outside the output root: {path}")
            data = path.read_bytes()
            questions = _source_questions(path, data)
            if questions is None:
                continue
            source_hashes[path] = hashlib.sha256(data).hexdigest()
            directory = path.parent
            while True:
                sections.setdefault(directory, []).extend(questions)
                if directory == root:
                    break
                directory = directory.parent

    _check_checkpoints(source_hashes)
    for path in existing_combined:
        if path.parent not in sections and _owned_combined(path):
            sections[path.parent] = []
    destinations = [
        directory / combined_name_for_directory(directory)
        for directory in sorted(sections)
    ]
    for destination in destinations:
        if destination.is_symlink() or (destination.exists() and not _owned_combined(destination)):
            raise ValueError(f"Refusing to overwrite an unrelated combined XML: {destination}")
    for path, expected_hash in source_hashes.items():
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected_hash:
            raise ValueError(f"XML changed while preparing combined output: {path}")
    for destination in destinations:
        content = PREFIX + "\n".join(sections[destination.parent]) + "\n</quiz>\n"
        _atomic_write(destination, content.encode("utf-8"))
    destination_set = set(destinations)
    for path in existing_combined:
        if path not in destination_set and _owned_combined(path):
            path.unlink()
    return destinations


def rebuild_combined_xml(output_root: Path) -> list[Path]:
    """Rebuild one combined import per output directory containing question XML."""
    root = Path(output_root).resolve()
    if not root.is_dir():
        raise ValueError(f"Output root is not a directory: {root}")
    lock = root / ".moodle-combiner.lock"
    try:
        handle = lock.open("x", encoding="utf-8")
    except FileExistsError as exc:
        raise ValueError(
            f"Another combination is running or left a stale lock: {lock}"
        ) from exc
    try:
        with handle:
            handle.write(f"{os.getpid()}\n")
        return _rebuild_combined_xml(root)
    finally:
        lock.unlink()
